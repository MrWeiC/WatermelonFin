import Foundation

/// One FIFO per player manager, shared by successive items. Captured operations retain
/// their originating client; sign-out cannot redirect a pending report to another user.
@MainActor
final class PlaybackReportQueue {
    private var tail: Task<Void, Never>?

    @discardableResult
    func enqueue(_ operation: @escaping @MainActor () async -> Void) -> Task<Void, Never> {
        let previous = tail
        let task = Task { @MainActor in
            await previous?.value
            await operation()
        }
        tail = task
        return task
    }
}
